





    CREATE TABLE IF NOT EXISTS users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email TEXT NOT NULL UNIQUE,
      name TEXT NOT NULL, password_hash TEXT NOT NULL,
      role TEXT NOT NULL DEFAULT 'customer' CHECK(role IN ('customer', 'admin')),
      created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
    );
    CREATE TABLE IF NOT EXISTS sessions (
      token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires_at BIGINT NOT NULL
    );
    CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires_at);
    CREATE TABLE IF NOT EXISTS products (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title TEXT NOT NULL, description TEXT NOT NULL,
      price DOUBLE PRECISION NOT NULL CHECK(price >= 0), "discountPercentage" DOUBLE PRECISION NOT NULL DEFAULT 0,
      rating DOUBLE PRECISION NOT NULL DEFAULT 0, stock BIGINT NOT NULL CHECK(stock >= 0),
      brand TEXT NOT NULL, category TEXT NOT NULL, thumbnail TEXT NOT NULL, images TEXT NOT NULL
    );
    CREATE INDEX IF NOT EXISTS products_category ON products(category);
    CREATE INDEX IF NOT EXISTS products_brand ON products(brand);
  

    CREATE TABLE IF NOT EXISTS account_items (
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      kind TEXT NOT NULL CHECK(kind IN ('cart','wishlist')),
      product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
      quantity BIGINT NOT NULL CHECK(quantity BETWEEN 1 AND 99),
      PRIMARY KEY(user_id, kind, product_id)
    );
    CREATE TABLE IF NOT EXISTS welcome_emails (
      user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
      message_key TEXT NOT NULL UNIQUE,
      status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','sent','failed')),
      attempts BIGINT NOT NULL DEFAULT 0, next_attempt BIGINT NOT NULL DEFAULT 0,
      first_attempt BIGINT, sent_at BIGINT, failure TEXT
    );
    CREATE TABLE IF NOT EXISTS catalog_imports (
      source_key TEXT PRIMARY KEY, product_id BIGINT REFERENCES products(id) ON DELETE SET NULL
    );
    CREATE TABLE IF NOT EXISTS orders (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id),
      request_key TEXT NOT NULL, request_body TEXT NOT NULL,
      shipping TEXT NOT NULL, total_cents BIGINT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','processing','shipped','delivered','cancelled')),
      payment_status TEXT NOT NULL DEFAULT 'unpaid' CHECK(payment_status IN ('unpaid','paid')),
      tracking TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
      UNIQUE(user_id, request_key)
    );
    CREATE INDEX IF NOT EXISTS orders_user ON orders(user_id, id);
    CREATE INDEX IF NOT EXISTS orders_status ON orders(status);
    CREATE INDEX IF NOT EXISTS orders_created_at ON orders(created_at);
    CREATE TABLE IF NOT EXISTS order_items (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id),
      product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
      title TEXT NOT NULL, unit_cents BIGINT NOT NULL, quantity BIGINT NOT NULL CHECK(quantity > 0)
    );
    CREATE INDEX IF NOT EXISTS order_items_order ON order_items(order_id);
  

    CREATE TABLE IF NOT EXISTS security_tokens (
      token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      kind TEXT NOT NULL CHECK(kind IN ('reset','verify')), expires_at BIGINT NOT NULL,
      UNIQUE(user_id, kind)
    );
    CREATE TABLE IF NOT EXISTS security_mail (
      id TEXT PRIMARY KEY, token_hash TEXT NOT NULL REFERENCES security_tokens(token_hash) ON DELETE CASCADE,
      payload TEXT, attempts BIGINT NOT NULL DEFAULT 0, next_attempt BIGINT NOT NULL DEFAULT 0,
      status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','sent','failed'))
    );
    CREATE TABLE IF NOT EXISTS mfa_challenges (
      token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires_at BIGINT NOT NULL, attempts BIGINT NOT NULL DEFAULT 0
    );
    CREATE TABLE IF NOT EXISTS recovery_codes (
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      code_hash TEXT NOT NULL, PRIMARY KEY(user_id, code_hash)
    );
    CREATE TABLE IF NOT EXISTS security_limits (
      key TEXT PRIMARY KEY, count BIGINT NOT NULL, expires_at BIGINT NOT NULL
    );
  
